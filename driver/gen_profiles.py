"""Generate mod/probe/src/mod/GeneratedProfiles.h from docs/offsets/*.json.

The JSON profiles are the single source of truth for version-specific data
(anchor signatures, struct field offsets, ECS component ids). Adding a game
version must not require editing C++:

    py -3.11 driver/gen_profiles.py           # rewrite the header
    py -3.11 driver/gen_profiles.py --check   # exit 1 when it is stale

``--check`` is what the unit tests run, so a profile edit without regeneration
fails CI instead of silently shipping stale offsets.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
PROFILE_DIR = ROOT / "docs" / "offsets"
HEADER = ROOT / "mod" / "probe" / "src" / "mod" / "GeneratedProfiles.h"


class ProfileError(ValueError):
    """A profile file cannot be turned into a C++ table entry."""


def _cpp_string(value: str) -> str:
    escaped = value.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{escaped}"'


def _offset_text(value: Any) -> str:
    if isinstance(value, str):
        return value
    if isinstance(value, int) and value >= 0:
        return hex(value)
    raise ProfileError(f"bad offset value {value!r}")


def load_profiles(directory: Path = PROFILE_DIR) -> list[dict[str, Any]]:
    """Read every ``*.json`` profile, sorted by version for stable output."""
    profiles: list[dict[str, Any]] = []
    seen: set[str] = set()
    for path in sorted(directory.glob("*.json")):
        try:
            data = json.loads(path.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            raise ProfileError(f"{path.name}: {exc}") from exc
        if not isinstance(data, dict):
            raise ProfileError(f"{path.name}: top level must be an object")
        version = data.get("version")
        build_id = data.get("build_id")
        if not isinstance(version, str) or not isinstance(build_id, str):
            # Not a runtime profile (notes, partial data); skip it.
            continue
        if data.get("runtime") is not True:
            # Historical reference files (e.g. the frida-era 1.26.45.01 dump)
            # use a different schema and must never be loaded at runtime.
            continue
        if build_id in seen:
            raise ProfileError(f"{path.name}: duplicate build_id {build_id!r}")
        seen.add(build_id)
        profiles.append(
            {
                "file": path.name,
                "version": version,
                "build_id": build_id,
                "version_prefix": str(data.get("version_prefix", "")),
                "anchors": data.get("anchors") or {},
                "structs": data.get("structs") or {},
                "components": data.get("components") or {},
            }
        )
    if not profiles:
        raise ProfileError(f"no profile with version/build_id under {directory}")
    profiles.sort(key=lambda item: item["build_id"])
    return profiles


def render(profiles: list[dict[str, Any]]) -> str:
    lines: list[str] = [
        "#pragma once",
        "",
        "// Generated by driver/gen_profiles.py from docs/offsets/*.json.",
        "// Do not edit by hand: edit the JSON profile and regenerate.",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <iterator>",
        "",
        "namespace probe::detail {",
        "",
        "struct ProfileAnchor {",
        "    char const* name;",
        "    char const* expectedHex;",
        "};",
        "",
        "struct ProfileField {",
        "    char const* type;",
        "    char const* field;",
        "    char const* offset;",
        "    bool        present;",
        "};",
        "",
        "struct ProfileComponent {",
        "    char const*   name;",
        "    std::uint32_t id;",
        "    std::uint32_t size;",
        "};",
        "",
        "struct VersionProfile {",
        "    char const*            version;",
        "    char const*            buildId;",
        "    char const*            versionPrefix;",
        "    ProfileAnchor const*   anchors;",
        "    std::size_t            anchorCount;",
        "    ProfileField const*    fields;",
        "    std::size_t            fieldCount;",
        "    ProfileComponent const* components;",
        "    std::size_t            componentCount;",
        "};",
        "",
    ]

    for index, profile in enumerate(profiles):
        anchors = profile["anchors"]
        anchor_rows: list[str] = []
        if isinstance(anchors, dict):
            for name in sorted(anchors):
                entry = anchors[name]
                expected = ""
                if isinstance(entry, dict):
                    expected = str(entry.get("expected_hex", "") or "")
                    kind = entry.get("kind")
                    if kind not in (None, "symbol"):
                        raise ProfileError(
                            f"{profile['file']}: anchor {name} has unsupported kind {kind!r}"
                        )
                anchor_rows.append(f"    {{{_cpp_string(str(name))}, {_cpp_string(expected)}}},")
        lines.append(f"inline constexpr ProfileAnchor kProfile{index}Anchors[] = {{")
        lines.extend(anchor_rows)
        if not anchor_rows:
            lines.append('    {"", ""},')
        lines.append("};")
        lines.append("")

        structs = profile["structs"]
        field_rows: list[str] = []
        if isinstance(structs, dict):
            for type_name in sorted(structs):
                fields = structs[type_name]
                if not isinstance(fields, dict):
                    continue
                for field_name in sorted(fields):
                    value = fields[field_name]
                    present = value is not None
                    offset = "0x0" if value is None else _offset_text(value)
                    field_rows.append(
                        "    {"
                        f"{_cpp_string(str(type_name))}, {_cpp_string(str(field_name))}, "
                        f"{_cpp_string(offset)}, {'true' if present else 'false'}"
                        "},"
                    )
        lines.append(f"inline constexpr ProfileField kProfile{index}Fields[] = {{")
        lines.extend(field_rows)
        if not field_rows:
            lines.append('    {"", "", "0x0", false},')
        lines.append("};")
        lines.append("")

        components = profile["components"]
        component_rows: list[str] = []
        if isinstance(components, dict):
            for name in sorted(components):
                entry = components[name]
                if not isinstance(entry, dict) or "id" not in entry or "size" not in entry:
                    raise ProfileError(f"{profile['file']}: component {name} needs id and size")
                component_rows.append(
                    f"    {{{_cpp_string(str(name))}, {int(entry['id'])}, {int(entry['size'])}}},"
                )
        lines.append(f"inline constexpr ProfileComponent kProfile{index}Components[] = {{")
        lines.extend(component_rows)
        if not component_rows:
            lines.append('    {"", 0, 0},')
        lines.append("};")
        lines.append("")

    lines.append("inline constexpr VersionProfile kProfiles[] = {")
    for index, profile in enumerate(profiles):
        fields = profile["structs"]
        field_count = (
            sum(len(value) for value in fields.values() if isinstance(value, dict))
            if isinstance(fields, dict)
            else 0
        )
        components = profile["components"]
        component_count = len(components) if isinstance(components, dict) else 0
        anchors = profile["anchors"]
        anchor_count = len(anchors) if isinstance(anchors, dict) else 0
        lines.append(
            "    {"
            f"{_cpp_string(profile['version'])}, {_cpp_string(profile['build_id'])}, "
            f"{_cpp_string(profile['version_prefix'])}, "
            f"kProfile{index}Anchors, {anchor_count}, "
            f"kProfile{index}Fields, {field_count}, "
            f"kProfile{index}Components, {component_count}"
            "},"
        )
    lines.append("};")
    lines.append("")
    lines.append("inline constexpr std::size_t kProfileCount = std::size(kProfiles);")
    lines.append("")
    lines.append("} // namespace probe::detail")
    lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when the header is stale")
    parser.add_argument("--out", type=Path, default=HEADER)
    args = parser.parse_args(argv)

    try:
        text = render(load_profiles())
    except ProfileError as exc:
        print(f"profile error: {exc}", file=sys.stderr)
        return 2

    current = args.out.read_text(encoding="utf-8") if args.out.exists() else ""
    if args.check:
        if current != text:
            print(f"stale: {args.out} (run driver/gen_profiles.py)", file=sys.stderr)
            return 1
        print(f"up to date: {args.out}")
        return 0

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
