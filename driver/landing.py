#!/usr/bin/env python3
"""Land one reverse-engineering round at a time.

The ledger is append-only.  ``probe`` records what was run, ``claim`` records
what was proven (with an evidence tier and static closure), ``end`` regenerates
the human-readable facts/resume files, and ``close`` runs the static gates.

Layout::

    <findings-root>/<version>/cases/<case>/
        case.json
        journal.jsonl
        facts.md          (generated)
        resume.md         (generated)
        report.md         (generated by close)
        probes/
"""

from __future__ import annotations

import argparse
import json
import os
import re
import subprocess
import sys
from datetime import UTC, datetime
from pathlib import Path
from typing import Any

ROOT = Path(__file__).resolve().parents[1]
SKILL_ROOT = ROOT / "skills" / "bedrock-re"
DEFAULT_FINDINGS = SKILL_ROOT / "findings"
DEFAULT_VERSION = "1.26.51.01"
KINDS = {"probe", "claim", "erratum", "dead-end", "decision", "abandon"}
RESULTS = {"confirmed", "refuted", "inconclusive", "live-only"}
TIERS = {"code", "constant", "live", "inference"}
SLUG = re.compile(r"^[a-z0-9][a-z0-9-]{0,63}$")
HEX_ADDRESS = re.compile(r"^0x[0-9A-Fa-f]{6,16}$")
MAX_RESUME_LINES = 200


class LandingError(ValueError):
    """A ledger operation is invalid."""


def now() -> str:
    return datetime.now(UTC).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def case_dir(findings_root: Path, version: str, case: str) -> Path:
    return findings_root / version / "cases" / case


def journal_path(findings_root: Path, version: str, case: str) -> Path:
    return case_dir(findings_root, version, case) / "journal.jsonl"


def write_json(path: Path, data: Any) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")


def read_case(findings_root: Path, version: str, case: str) -> dict[str, Any]:
    path = case_dir(findings_root, version, case) / "case.json"
    if not path.exists():
        raise LandingError(f"case not found: {case} (run begin first)")
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except json.JSONDecodeError as exc:
        raise LandingError(f"{path}: {exc}") from exc
    if not isinstance(data, dict):
        raise LandingError(f"{path}: case.json must be an object")
    return data


def read_journal(findings_root: Path, version: str, case: str) -> list[dict[str, Any]]:
    path = journal_path(findings_root, version, case)
    if not path.exists():
        return []
    records: list[dict[str, Any]] = []
    for line_no, line in enumerate(path.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        try:
            record = json.loads(line)
        except json.JSONDecodeError as exc:
            raise LandingError(f"{path}:{line_no}: {exc}") from exc
        if not isinstance(record, dict):
            raise LandingError(f"{path}:{line_no}: record must be an object")
        records.append(record)
    return records


def append_record(
    findings_root: Path, version: str, case: str, record: dict[str, Any]
) -> dict[str, Any]:
    path = journal_path(findings_root, version, case)
    path.parent.mkdir(parents=True, exist_ok=True)
    existing = {item.get("id") for item in read_journal(findings_root, version, case)}
    if record.get("id") in existing:
        raise LandingError(f"duplicate journal id: {record.get('id')}")
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(record, ensure_ascii=False) + "\n")
    return record


def next_seq(records: list[dict[str, Any]]) -> int:
    values = [int(item["seq"]) for item in records if isinstance(item.get("seq"), int)]
    return max(values, default=0) + 1


def record_id(round_no: int, seq: int) -> str:
    return f"r{round_no:02d}-{seq:03d}"


def probe_refs(record: dict[str, Any]) -> set[str]:
    ref = record.get("probe_ref")
    if isinstance(ref, str):
        return {ref}
    if isinstance(ref, list):
        return {item for item in ref if isinstance(item, str)}
    return set()


def pending_probes(records: list[dict[str, Any]]) -> list[dict[str, Any]]:
    probes = {
        str(item.get("id")): item
        for item in records
        if item.get("kind") == "probe" and item.get("id")
    }
    closed: set[str] = set()
    for record in records:
        if record.get("kind") in {"claim", "erratum", "abandon", "dead-end"}:
            closed.update(probe_refs(record))
    return [probe for ident, probe in probes.items() if ident not in closed]


def update_case(findings_root: Path, version: str, case: str, **changes: Any) -> dict[str, Any]:
    data = read_case(findings_root, version, case)
    data.update(changes)
    data["updated_at"] = now()
    write_json(case_dir(findings_root, version, case) / "case.json", data)
    return data


def rel_path(path: Path, root: Path = ROOT) -> str:
    try:
        return path.resolve().relative_to(root.resolve()).as_posix()
    except ValueError:
        return path.as_posix()


def generate_facts(findings_root: Path, version: str, case: str) -> Path:
    data = read_case(findings_root, version, case)
    records = read_journal(findings_root, version, case)
    path = case_dir(findings_root, version, case) / "facts.md"
    lines = [
        f"# {case} — facts",
        "",
        "<!-- generated by driver/landing.py; do not edit -->",
        "",
        f"- version: `{version}`",
        f"- goal: {data.get('goal', '')}",
        f"- current round: {data.get('current_round', 1)}",
        f"- updated: {now()}",
        "",
    ]
    by_round: dict[int, list[dict[str, Any]]] = {}
    for record in records:
        round_no = int(record.get("round", 0))
        by_round.setdefault(round_no, []).append(record)
    for round_no in sorted(by_round):
        lines.append(f"## Round {round_no}")
        lines.append("")
        for record in sorted(by_round[round_no], key=lambda item: int(item.get("seq", 0))):
            kind = record.get("kind")
            ident = record.get("id", "?")
            if kind == "probe":
                probe = record.get("probe") or {}
                lines.append(f"### {ident} probe — {probe.get('scope', '')}")
                lines.append("")
                lines.append(f"- origin: {record.get('origin')}")
                lines.append(f"- script: `{probe.get('script', '')}`")
                lines.append(f"- output: `{probe.get('output', '')}`")
                lines.append(f"- exit: {probe.get('exit_code')}")
                lines.append("")
                continue
            if kind == "abandon":
                lines.append(f"### {ident} abandon")
                lines.append("")
                lines.append(f"- reason: {record.get('reason', '')}")
                lines.append(f"- probes: {', '.join(sorted(probe_refs(record))) or '-'}")
                lines.append("")
                continue
            result = record.get("result", "inconclusive")
            lines.append(f"### {ident} {kind} — {result}")
            lines.append("")
            if record.get("hypothesis"):
                lines.append(f"- hypothesis: {record['hypothesis']}")
            if record.get("probe_ref"):
                lines.append(f"- probe: {record['probe_ref']}")
            if record.get("evidence_tier"):
                lines.append(f"- evidence tier: `{record['evidence_tier']}`")
            if record.get("static_closure"):
                lines.append(f"- static closure: {record['static_closure']}")
            if record.get("evidence"):
                lines.append(f"- evidence: {record['evidence']}")
            roles = record.get("roles") or {}
            if roles:
                lines.append(
                    "- roles: " + ", ".join(f"`{name}` = `{addr}`" for name, addr in roles.items())
                )
            if record.get("next"):
                lines.append(f"- next: {record['next']}")
            if record.get("published"):
                lines.append(f"- published: {record['published']}")
            if record.get("erratum_of"):
                lines.append(f"- erratum_of: {record['erratum_of']}")
            lines.append("")
    pending = pending_probes(records)
    lines.append("## Pending probes")
    lines.append("")
    if pending:
        for probe in pending:
            lines.append(f"- {probe.get('id')}: {(probe.get('probe') or {}).get('scope', '')}")
    else:
        lines.append("- none")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def generate_resume(findings_root: Path, version: str, case: str) -> Path:
    data = read_case(findings_root, version, case)
    records = read_journal(findings_root, version, case)
    path = case_dir(findings_root, version, case) / "resume.md"
    confirmed = [item for item in records if item.get("result") == "confirmed"]
    open_items = [
        item
        for item in records
        if item.get("result") in {"inconclusive", "live-only"} and item.get("kind") != "probe"
    ]
    pending = pending_probes(records)
    lines = [
        f"# resume: {case}",
        "",
        f"- version: `{version}`",
        f"- goal: {data.get('goal', '')}",
        f"- environment: {data.get('environment', '') or '-'}",
        f"- current round: {data.get('current_round', 1)}",
        f"- last record: {records[-1].get('id') if records else '-'}",
        f"- journal: `{rel_path(journal_path(findings_root, version, case))}`",
        "",
        "## Confirmed (static closure required)",
        "",
    ]
    if confirmed:
        for item in confirmed[-12:]:
            lines.append(
                f"- {item.get('id')}: {item.get('hypothesis', '')} "
                f"[{item.get('evidence_tier')}; {item.get('static_closure', '')}]"
            )
    else:
        lines.append("- none")
    lines += ["", "## Open / pending", ""]
    if open_items:
        for item in open_items[-10:]:
            lines.append(f"- {item.get('id')}: {item.get('hypothesis', '')} ({item.get('result')})")
    else:
        lines.append("- none")
    if pending:
        lines.append("")
        lines.append("Pending probes:")
        for probe in pending:
            lines.append(f"- {probe.get('id')}: {(probe.get('probe') or {}).get('scope', '')}")
    next_actions = [item.get("next") for item in records if item.get("next")]
    lines += ["", "## Next actions", ""]
    if next_actions:
        for action in next_actions[-3:]:
            lines.append(f"- {action}")
    else:
        lines.append("- fill in the next hypothesis")
    lines += [
        "",
        "## Pointers",
        "",
        f"- facts: `{rel_path(case_dir(findings_root, version, case) / 'facts.md')}`",
        f"- old account: `{rel_path(case_dir(findings_root, version, case) / 'old-account.md')}`",
        f"- probes: `{rel_path(case_dir(findings_root, version, case) / 'probes')}`",
        "",
    ]
    text = "\n".join(lines)
    if len(text.splitlines()) > MAX_RESUME_LINES:
        text = "\n".join(text.splitlines()[:MAX_RESUME_LINES]) + "\n"
    path.write_text(text, encoding="utf-8")
    return path


def search_old_ledger(findings_root: Path, version: str, case: str, goal: str) -> Path:
    """Grep the existing docs/ledger before starting; write old-account.md."""
    terms = {case.lower()}
    for token in re.findall(r"[A-Za-z0-9_]{4,}", goal):
        terms.add(token.lower())
    candidates: list[Path] = [
        *sorted((ROOT / "docs").glob("*.md")),
        ROOT / "AGENTS.md",
        ROOT / "mod" / "README.md",
    ]
    candidates.extend(
        path
        for path in sorted(findings_root.glob("*/cases/*/facts.md"))
        if path.parent.name != case
    )
    matches: list[str] = []
    for path in candidates:
        if not path.exists():
            continue
        try:
            lines = path.read_text(encoding="utf-8", errors="ignore").splitlines()
        except OSError:
            continue
        for line_no, line in enumerate(lines, 1):
            lowered = line.lower()
            if any(term in lowered for term in terms):
                matches.append(f"- `{rel_path(path)}:{line_no}`: {line.strip()[:200]}")
                if len(matches) >= 20:
                    break
        if len(matches) >= 20:
            break
    git_lines: list[str] = []
    try:
        completed = subprocess.run(
            ["git", "log", "--oneline", "-20", "--grep", case],
            cwd=ROOT,
            capture_output=True,
            text=True,
            check=False,
        )
    except OSError:
        completed = None
    if completed is not None and completed.returncode == 0 and completed.stdout.strip():
        git_lines = [f"- `{line.strip()}`" for line in completed.stdout.splitlines()]
    path = case_dir(findings_root, version, case) / "old-account.md"
    lines = [
        f"# old account — {case}",
        "",
        "<!-- generated by driver/landing.py begin; check before redoing work -->",
        "",
        f"- search terms: {', '.join(sorted(terms))}",
        "",
        "## docs / prior ledgers",
        "",
    ]
    lines.extend(matches or ["- no match"])
    lines += ["", "## git log", ""]
    lines.extend(git_lines or ["- no match"])
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")
    return path


def begin(args: argparse.Namespace) -> int:
    if not SLUG.match(args.case):
        raise LandingError("case must match ^[a-z0-9][a-z0-9-]{0,63}$")
    version = args.version
    directory = case_dir(args.findings_root, version, args.case)
    case_file = directory / "case.json"
    records = read_journal(args.findings_root, version, args.case)
    pending = pending_probes(records)
    if pending and not args.force:
        ids = ", ".join(str(item.get("id")) for item in pending)
        raise LandingError(f"previous round has pending probes ({ids}); claim/abandon first")
    directory.mkdir(parents=True, exist_ok=True)
    (directory / "probes").mkdir(exist_ok=True)
    if not case_file.exists():
        write_json(
            case_file,
            {
                "case": args.case,
                "version": version,
                "goal": args.goal,
                "environment": args.environment,
                "current_round": 1,
                "status": "open",
                "created_at": now(),
                "updated_at": now(),
            },
        )
    else:
        update_case(
            args.findings_root,
            version,
            args.case,
            goal=args.goal or read_case(args.findings_root, version, args.case).get("goal", ""),
            status="open",
        )
    facts = generate_facts(args.findings_root, version, args.case)
    resume = generate_resume(args.findings_root, version, args.case)
    old_account = search_old_ledger(args.findings_root, version, args.case, args.goal)
    print(
        json.dumps(
            {
                "event": "begin",
                "case": args.case,
                "facts": str(facts),
                "resume": str(resume),
                "old_account": str(old_account),
            },
            ensure_ascii=False,
        )
    )
    return 0


def write_probe_files(directory: Path, ident: str, command: list[str]) -> tuple[Path, Path | None]:
    probes = directory / "probes"
    probes.mkdir(parents=True, exist_ok=True)
    cmd_path = probes / f"{ident}.cmd"
    cmd_path.write_text(subprocess.list2cmdline(command) + "\n", encoding="utf-8")
    script_path: Path | None = None
    for item in command:
        candidate = Path(item)
        if candidate.suffix == ".py" and candidate.is_file():
            script_path = probes / f"{ident}.py"
            script_path.write_text(candidate.read_text(encoding="utf-8"), encoding="utf-8")
            break
    return cmd_path, script_path


def probe(args: argparse.Namespace) -> int:
    data = read_case(args.findings_root, args.version, args.case)
    if data.get("status") != "open":
        raise LandingError(f"case is not open: {args.case}")
    if not args.scope or not args.scope.strip():
        raise LandingError("probe needs --scope so a negative result has a search boundary")
    command = list(args.command)
    if command and command[0] == "--":
        command = command[1:]
    if not command:
        raise LandingError("probe needs a command after --")
    records = read_journal(args.findings_root, args.version, args.case)
    round_no = args.round if args.round is not None else int(data.get("current_round", 1))
    seq = next_seq(records)
    ident = record_id(round_no, seq)
    directory = case_dir(args.findings_root, args.version, args.case)
    cmd_path, script_path = write_probe_files(directory, ident, command)
    started = now()
    exit_code = -1
    stdout = ""
    stderr = ""
    try:
        completed = subprocess.run(
            command,
            cwd=ROOT,
            capture_output=True,
            text=True,
            timeout=args.timeout,
            check=False,
        )
        exit_code = completed.returncode
        stdout = completed.stdout
        stderr = completed.stderr
    except subprocess.TimeoutExpired as exc:
        stdout = str(exc.stdout or "")
        stderr = str(exc.stderr or "") + f"\n[landing] timeout after {args.timeout}s\n"
    out_path = directory / "probes" / f"{ident}.out"
    out_path.write_text(
        "\n".join(
            [
                f"# command: {subprocess.list2cmdline(command)}",
                "# cwd: <repo>",
                f"# started: {started}",
                f"# exit: {exit_code}",
                "# --- stdout ---",
                stdout,
                "# --- stderr ---",
                stderr,
                "",
            ]
        ),
        encoding="utf-8",
    )
    params = {}
    for item in args.param or []:
        if "=" not in item:
            raise LandingError(f"--param must be key=value: {item}")
        key, value = item.split("=", 1)
        params[key] = value
    record = {
        "id": ident,
        "round": round_no,
        "seq": seq,
        "ts": started,
        "version": args.version,
        "case": args.case,
        "session": f"landing-{os.getpid()}",
        "kind": "probe",
        "origin": "tool",
        "hypothesis": args.scope or "",
        "probe": {
            "script": rel_path(script_path or cmd_path),
            "output": rel_path(out_path),
            "scenario": args.scenario or "",
            "command": subprocess.list2cmdline(command),
            "scope": args.scope or "",
            "params": params,
            "limit": args.limit,
            "exit_code": exit_code,
        },
        "result": None,
        "evidence_tier": None,
        "static_closure": None,
        "evidence": None,
        "roles": {},
        "next": None,
        "erratum_of": None,
        "probe_ref": None,
    }
    append_record(args.findings_root, args.version, args.case, record)
    update_case(args.findings_root, args.version, args.case)
    print(
        json.dumps(
            {"event": "probe", "id": ident, "exit": exit_code, "output": str(out_path)},
            ensure_ascii=False,
        )
    )
    return 0 if exit_code == 0 else 1


def load_claims(path: Path) -> list[dict[str, Any]]:
    text = path.read_text(encoding="utf-8")
    if path.suffix.lower() == ".json":
        try:
            data = json.loads(text)
        except json.JSONDecodeError as exc:
            raise LandingError(f"{path}: {exc}") from exc
    else:
        try:
            import yaml
        except ImportError as exc:  # pragma: no cover - PyYAML is present here
            raise LandingError("PyYAML is required for .yaml claims; use .json") from exc
        try:
            data = yaml.safe_load(text)
        except yaml.YAMLError as exc:
            raise LandingError(f"{path}: {exc}") from exc
    if isinstance(data, dict) and "claims" in data:
        data = data["claims"]
    if isinstance(data, dict):
        data = [data]
    if not isinstance(data, list):
        raise LandingError("claims file must be a list or {claims: [...]}")
    return [item for item in data if isinstance(item, dict)]


def validate_claim(claim: dict[str, Any], known_ids: set[str]) -> None:
    if not isinstance(claim.get("hypothesis"), str) or not claim["hypothesis"].strip():
        raise LandingError("claim.hypothesis must be a non-empty string")
    result = claim.get("result")
    if result not in RESULTS:
        raise LandingError(f"claim.result must be one of {sorted(RESULTS)}")
    tier = claim.get("evidence_tier")
    if tier not in TIERS:
        raise LandingError(f"claim.evidence_tier must be one of {sorted(TIERS)}")
    evidence = claim.get("evidence")
    if not isinstance(evidence, str) or not evidence.strip():
        raise LandingError("claim.evidence must be a non-empty string")
    closure = claim.get("static_closure")
    if result == "confirmed":
        if tier not in {"code", "constant"}:
            raise LandingError("confirmed claim needs evidence_tier code/constant")
        if not isinstance(closure, str) or not closure.strip():
            raise LandingError("confirmed claim needs static_closure")
    if tier in {"code", "constant"} and not isinstance(closure, str):
        raise LandingError(f"{tier} claim needs static_closure")
    if "published" in claim:
        published = claim["published"]
        if not isinstance(published, str):
            raise LandingError("claim.published must be a string")
        target = published.split("#", 1)[0]
        if target and not (ROOT / target).exists():
            raise LandingError(f"claim.published target does not exist: {target}")
    kind = claim.get("kind")
    if kind is not None and kind not in {"claim", "dead-end", "decision"}:
        raise LandingError("claim.kind must be claim/dead-end/decision")
    roles = claim.get("roles") or {}
    if not isinstance(roles, dict):
        raise LandingError("claim.roles must be an object")
    for name, address in roles.items():
        if not isinstance(name, str) or not name.startswith("@"):
            raise LandingError(f"role name must start with @: {name!r}")
        if address is not None and (not isinstance(address, str) or not HEX_ADDRESS.match(address)):
            raise LandingError(f"{name}: address must be 0x... or null")
    ref = claim.get("probe_ref")
    refs = probe_refs(claim)
    missing = refs - known_ids
    if missing:
        raise LandingError(f"unknown probe_ref: {', '.join(sorted(missing))}")
    if isinstance(ref, list) and not ref:
        raise LandingError("probe_ref list must not be empty")


def claim(args: argparse.Namespace) -> int:
    data = read_case(args.findings_root, args.version, args.case)
    if data.get("status") != "open":
        raise LandingError(f"case is not open: {args.case}")
    items = load_claims(args.file)
    if not items:
        raise LandingError("claims file is empty")
    records = read_journal(args.findings_root, args.version, args.case)
    known_ids = {str(item.get("id")) for item in records}
    for item in items:
        validate_claim(item, known_ids)
    count = 0
    for item in items:
        round_no = int(item.get("round") or data.get("current_round", 1))
        seq = next_seq(records)
        ident = record_id(round_no, seq)
        record = {
            "id": ident,
            "round": round_no,
            "seq": seq,
            "ts": now(),
            "version": args.version,
            "case": args.case,
            "session": f"landing-{os.getpid()}",
            "kind": "erratum" if item.get("erratum_of") else (item.get("kind") or "claim"),
            "origin": "manual",
            "hypothesis": item["hypothesis"],
            "probe": None,
            "result": item["result"],
            "evidence_tier": item["evidence_tier"],
            "static_closure": item.get("static_closure"),
            "evidence": item["evidence"],
            "roles": item.get("roles") or {},
            "next": item.get("next"),
            "published": item.get("published"),
            "erratum_of": item.get("erratum_of"),
            "probe_ref": item.get("probe_ref"),
        }
        append_record(args.findings_root, args.version, args.case, record)
        records.append(record)
        count += 1
    update_case(args.findings_root, args.version, args.case)
    print(json.dumps({"event": "claim", "count": count}, ensure_ascii=False))
    return 0


def end(args: argparse.Namespace) -> int:
    data = read_case(args.findings_root, args.version, args.case)
    if data.get("status") != "open":
        raise LandingError(f"case is not open: {args.case}")
    facts = generate_facts(args.findings_root, args.version, args.case)
    resume = generate_resume(args.findings_root, args.version, args.case)
    current = int(data.get("current_round", 1))
    update_case(args.findings_root, args.version, args.case, current_round=current + 1)
    print(
        json.dumps(
            {"event": "end", "facts": str(facts), "resume": str(resume), "next_round": current + 1},
            ensure_ascii=False,
        )
    )
    return 0


def abandon(args: argparse.Namespace) -> int:
    data = read_case(args.findings_root, args.version, args.case)
    if data.get("status") != "open":
        raise LandingError(f"case is not open: {args.case}")
    records = read_journal(args.findings_root, args.version, args.case)
    pending = pending_probes(records)
    targets = pending
    if args.probe:
        wanted = set(args.probe)
        targets = [item for item in pending if item.get("id") in wanted]
        missing = wanted - {str(item.get("id")) for item in targets}
        if missing:
            raise LandingError(f"not pending: {', '.join(sorted(missing))}")
    if not targets:
        raise LandingError("no pending probes to abandon")
    for item in targets:
        round_no = int(item.get("round", 1))
        seq = next_seq(records)
        record = {
            "id": record_id(round_no, seq),
            "round": round_no,
            "seq": seq,
            "ts": now(),
            "version": args.version,
            "case": args.case,
            "session": f"landing-{os.getpid()}",
            "kind": "abandon",
            "origin": "manual",
            "hypothesis": (item.get("probe") or {}).get("scope", ""),
            "probe": None,
            "result": "inconclusive",
            "evidence_tier": "inference",
            "static_closure": None,
            "evidence": args.reason,
            "roles": {},
            "next": None,
            "erratum_of": None,
            "probe_ref": item.get("id"),
            "reason": args.reason,
        }
        append_record(args.findings_root, args.version, args.case, record)
        records.append(record)
    update_case(args.findings_root, args.version, args.case)
    print(json.dumps({"event": "abandon", "count": len(targets)}, ensure_ascii=False))
    return 0


def run_check(command: list[str]) -> tuple[int, str]:
    completed = subprocess.run(command, cwd=ROOT, capture_output=True, text=True, check=False)
    output = (completed.stdout + completed.stderr).strip()
    return completed.returncode, output


def close(args: argparse.Namespace) -> int:
    data = read_case(args.findings_root, args.version, args.case)
    if data.get("status") not in {"open", "closed"}:
        raise LandingError(f"case status is {data.get('status')!r}")
    checks: list[tuple[str, int, str]] = []
    report_check = [
        sys.executable,
        str(SKILL_ROOT / "checks" / "lint_report.py"),
        "--version",
        args.version,
        "--case",
        args.case,
        "--findings-root",
        str(args.findings_root),
    ]
    checks.append(("lint_report", *run_check(report_check)))
    static_checks = [
        ("lint_skill", SKILL_ROOT / "checks" / "lint_skill.py"),
        ("check_roles", SKILL_ROOT / "checks" / "guards" / "check_roles.py"),
        ("check_statevector", SKILL_ROOT / "checks" / "guards" / "check_statevector.py"),
        ("check_eye_feet", SKILL_ROOT / "checks" / "guards" / "check_eye_feet.py"),
        ("check_sprint_boost", SKILL_ROOT / "checks" / "guards" / "check_sprint_boost.py"),
    ]
    for name, path in static_checks:
        checks.append((name, *run_check([sys.executable, str(path)])))
    if not args.skip_public:
        public_check = [
            sys.executable,
            str(SKILL_ROOT / "checks" / "lint_public.py"),
            "--root",
            str(ROOT),
        ]
        checks.append(("lint_public", *run_check(public_check)))
    if not args.skip_tests:
        checks.append(
            (
                "test_profiles",
                *run_check([sys.executable, "-m", "unittest", "tests.test_profiles", "-v"]),
            )
        )
    generate_facts(args.findings_root, args.version, args.case)
    generate_resume(args.findings_root, args.version, args.case)
    records = read_journal(args.findings_root, args.version, args.case)
    report = case_dir(args.findings_root, args.version, args.case) / "report.md"
    confirmed = [item for item in records if item.get("result") == "confirmed"]
    other = [
        item for item in records if item.get("result") in {"refuted", "inconclusive", "live-only"}
    ]
    probes = [item for item in records if item.get("kind") == "probe"]
    lines = [
        f"# {args.case} — report",
        "",
        "<!-- generated by driver/landing.py close -->",
        "",
        f"- version: `{args.version}`",
        f"- generated: {now()}",
        "- checks: "
        + ", ".join(f"{name}={'ok' if code == 0 else 'FAIL'}" for name, code, _ in checks),
        "",
        "## A. 静态结论（confirmed）",
        "",
    ]
    if confirmed:
        for item in confirmed:
            lines.append(f"### {item.get('id')} — {item.get('hypothesis', '')}")
            lines.append("")
            lines.append(f"- tier: `{item.get('evidence_tier')}`")
            lines.append(f"- static closure: {item.get('static_closure')}")
            lines.append(f"- evidence: {item.get('evidence')}")
            if item.get("roles"):
                lines.append("- roles: " + ", ".join(f"`{k}`" for k in item["roles"]))
            lines.append("")
    else:
        lines += ["- none", ""]
    lines += ["## B. 未定/撤回/下一步", ""]
    if other:
        for item in other:
            lines.append(
                f"- {item.get('id')}: {item.get('result')} — {item.get('hypothesis', '')}"
                + (f" (next: {item['next']})" if item.get("next") else "")
            )
    else:
        lines.append("- none")
    lines += ["", "## C. 原始证据", ""]
    for item in probes:
        probe_data = item.get("probe") or {}
        lines.append(
            f"- {item.get('id')}: exit={probe_data.get('exit_code')} "
            f"script=`{probe_data.get('script')}` output=`{probe_data.get('output')}`"
        )
    lines.append("")
    report.write_text("\n".join(lines), encoding="utf-8")
    failures = [name for name, code, _ in checks if code != 0]
    if failures:
        print(
            json.dumps(
                {"event": "close", "ok": False, "failed": failures, "report": str(report)},
                ensure_ascii=False,
            )
        )
        return 1
    update_case(args.findings_root, args.version, args.case, status="closed")
    print(json.dumps({"event": "close", "ok": True, "report": str(report)}, ensure_ascii=False))
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--findings-root",
        type=Path,
        default=DEFAULT_FINDINGS,
        help=argparse.SUPPRESS,
    )
    parser.add_argument("--version", default=DEFAULT_VERSION)
    sub = parser.add_subparsers(dest="command", required=True)

    p_begin = sub.add_parser("begin", help="start a case")
    p_begin.add_argument("--case", required=True)
    p_begin.add_argument("--goal", default="")
    p_begin.add_argument("--environment", default="")
    p_begin.add_argument("--force", action="store_true")
    p_begin.set_defaults(func=begin)

    p_probe = sub.add_parser("probe", help="run a probe and journal it")
    p_probe.add_argument("--case", required=True)
    p_probe.add_argument("--scope", default="")
    p_probe.add_argument("--scenario", default="")
    p_probe.add_argument("--round", type=int)
    p_probe.add_argument("--param", action="append", help="key=value")
    p_probe.add_argument("--limit", type=int, default=200)
    p_probe.add_argument("--timeout", type=float, default=600.0)
    p_probe.add_argument("command", nargs=argparse.REMAINDER)
    p_probe.set_defaults(func=probe)

    p_claim = sub.add_parser("claim", help="append claims from a JSON/YAML file")
    p_claim.add_argument("--case", required=True)
    p_claim.add_argument("--file", type=Path, required=True)
    p_claim.set_defaults(func=claim)

    p_end = sub.add_parser("end", help="regenerate facts/resume and advance the round")
    p_end.add_argument("--case", required=True)
    p_end.set_defaults(func=end)

    p_close = sub.add_parser("close", help="run checks and write the three-part report")
    p_close.add_argument("--case", required=True)
    p_close.add_argument("--skip-public", action="store_true")
    p_close.add_argument("--skip-tests", action="store_true")
    p_close.set_defaults(func=close)

    p_abandon = sub.add_parser("abandon", help="close pending probes without claiming them")
    p_abandon.add_argument("--case", required=True)
    p_abandon.add_argument("--reason", required=True)
    p_abandon.add_argument("--probe", action="append")
    p_abandon.set_defaults(func=abandon)
    return parser


def main(argv: list[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    try:
        return int(args.func(args))
    except LandingError as exc:
        print(f"landing: {exc}", file=sys.stderr)
        return 2
    except subprocess.TimeoutExpired:
        print("landing: probe timed out", file=sys.stderr)
        return 1


if __name__ == "__main__":
    raise SystemExit(main())
